/* ============================================
   Taalwisselaar — initialisatie & logica
   ============================================ */

(function () {
  const STORAGE_KEY = 'ns12_lang';
  const DEFAULT_LANG = 'es';

  function getCurrentLang() {
    return localStorage.getItem(STORAGE_KEY) || DEFAULT_LANG;
  }

  function applyLang(lang) {
    const t = TRANSLATIONS[lang];
    if (!t) return;

    /* Sla taal op */
    localStorage.setItem(STORAGE_KEY, lang);

    /* Zet html[lang] — belangrijk voor Google Translate */
    document.documentElement.lang = lang;

    /* Vertaal alle data-i18n elementen (textContent) */
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (t[key] !== undefined) {
        el.textContent = t[key];
        /* Markeer als niet-vertaalbaar zodat Google Translate dit overslaat */
        el.setAttribute('translate', 'no');
      }
    });

    /* Vertaal alle data-i18n-href elementen (href attribuut) */
    document.querySelectorAll('[data-i18n-href]').forEach(el => {
      const key = el.getAttribute('data-i18n-href');
      if (t[key] !== undefined) el.href = t[key];
    });

    /* Markeer actieve taalknop */
    document.querySelectorAll('.lang-switch a').forEach(a => {
      a.classList.toggle('active', a.getAttribute('data-lang') === lang);
    });
  }

  /* Koppel knoppen */
  function initSwitcher() {
    document.querySelectorAll('.lang-switch a[data-lang]').forEach(a => {
      a.addEventListener('click', e => {
        e.preventDefault();
        applyLang(a.getAttribute('data-lang'));
      });
    });

    /* Pas direct toe bij laden */
    applyLang(getCurrentLang());

    /* Mobiele navigatie initialiseren */
    initMobileNav();
  }

  /* Mobile navigatie toggle & buiten-klik sluiten */
  function initMobileNav() {
    const toggle = document.querySelector('.nav-toggle');
    const links = document.querySelector('.nav-links');
    if (!toggle || !links) return;

    toggle.onclick = function(e) {
      if (e) e.stopPropagation();
      const isOpen = links.classList.toggle('open');
      toggle.classList.toggle('open', isOpen);
    };

    links.querySelectorAll('a').forEach(a => {
      a.addEventListener('click', () => {
        links.classList.remove('open');
        toggle.classList.remove('open');
      });
    });

    document.addEventListener('click', (e) => {
      if (!links.contains(e.target) && !toggle.contains(e.target)) {
        links.classList.remove('open');
        toggle.classList.remove('open');
      }
    });
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initSwitcher);
  } else {
    initSwitcher();
  }
})();
